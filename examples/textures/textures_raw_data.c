#include "raylib.h"

//------------------------------------------------------------------------------------
// Program main entry point
//------------------------------------------------------------------------------------
int main(void)
{
    // Initialization
    //--------------------------------------------------------------------------------------
    const int screenWidth = 800;
    const int screenHeight = 450;

    InitWindow(screenWidth, screenHeight, "raylib [textures] example - raw data");

    // NOTE: Textures MUST be loaded after Window initialization (OpenGL context is required)

    // Load RAW image data (512x512, 32bit RGBA, no file header)
    Image imFudesumiRaw = LoadImageRaw("resources/fudesumi.raw", 384, 512, PIXELFORMAT_UNCOMPRESSED_R8G8B8A8, 0);
    Texture2D texFudesumi = LoadTextureFromImage(imFudesumiRaw);  // Upload CPU (RAM) image to GPU (VRAM)
    UnloadImage(imFudesumiRaw);                                // Unload CPU (RAM) image data

    // Generate a checked texture by code
    int imWidth = 960;
    int imHeight = 480;

    // Dynamic memory allocation to store pixels data (Color type)
    // WARNING: Using raylib provided MemAlloc() that uses default raylib
    // internal memory allocator, so this data can be freed using UnloadImage()
    // that also uses raylib internal memory de-allocator
    Color *pixels = (Color *)MemAlloc(imWidth*imHeight*sizeof(Color));

    for (int y = 0; y < imHeight; y++)
    {
        for (int x = 0; x < imWidth; x++)
        {
            if (((x/32+y/32)/1)%2 == 0) pixels[y*imWidth + x] = ORANGE;
            else pixels[y*imWidth + x] = GOLD;
        }
    }

    // Load pixels data into an image structure and create texture
    // NOTE: We can assign pixels directly to data because Color is R8G8B8A8
    // data structure defining that pixelformat, format must be set properly
    Image imChecked = {
        .data = pixels,
        .width = imWidth,
        .height = imHeight,
        .format = PIXELFORMAT_UNCOMPRESSED_R8G8B8A8,
        .mipmaps = 1
    };

    Texture2D texChecked = LoadTextureFromImage(imChecked);
    UnloadImage(imChecked);         // Unload CPU (RAM) image data (pixels)

    SetTargetFPS(60);               // Set our game to run at 60 frames-per-second
    //---------------------------------------------------------------------------------------

    // Main game loop
    while (!WindowShouldClose())    // Detect window close button or ESC key
    {
        // Update
        //----------------------------------------------------------------------------------
        // TODO: Update your variables here
        //----------------------------------------------------------------------------------

        // Draw
        //----------------------------------------------------------------------------------
        BeginDrawing();

            ClearBackground(RAYWHITE);

            DrawTexture(texChecked, screenWidth/2 - texChecked.width/2, screenHeight/2 - texChecked.height/2, Fade(WHITE, 0.5f));
            DrawTexture(texFudesumi, 430, -30, WHITE);

            DrawText("CHECKED TEXTURE ", 84, 85, 30, BROWN);
            DrawText("GENERATED by CODE", 72, 148, 30, BROWN);
            DrawText("and RAW IMAGE LOADING", 46, 210, 30, BROWN);

            DrawText("(c) Fudesumi sprite by Eiden Marsal", 310, screenHeight - 20, 10, BROWN);

        EndDrawing();
        //----------------------------------------------------------------------------------
    }

    // De-Initialization
    //--------------------------------------------------------------------------------------
    UnloadTexture(texFudesumi);    // Texture unloading
    UnloadTexture(texChecked);     // Texture unloading

    CloseWindow();              // Close window and OpenGL context
    //--------------------------------------------------------------------------------------

    return 0;
}